"""The audit emitter: what one `emit()` call writes, refuses, and never breaks.

Requirements exercised: FR-A-02 (fixed schema, a write missing a required field
is rejected), FR-A-04 (no student data), FR-A-11 (logging failure never fails
the user action), X-4 (a student's email, address and browser are never stored)
and X-5 (the trace id is generated by the server, the client's id is kept as
untrusted context only).
"""

