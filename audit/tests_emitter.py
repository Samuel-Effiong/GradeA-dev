def make_user(email, user_type=UserTypes.TEACHER, school=None):
    return CustomUser.objects.create_user(
        email=email,
        password=PASSWORD,
        user_type=user_type,
        first_name="Test",
        last_name="User",
        school=school,
    )


def call(**over):
    """A minimal valid emit() call."""
    args = {"actor": None, "target_type": "Assignment", "target_id": uuid.uuid4()}
    args.update(over)
    return emit(AuditAction.ASSIGNMENT_COPY, **args)


def request(**meta):
    return RequestFactory().get("/", **meta)


class WhatOneEventRecordsTest(TestCase):
    school: School
    teacher: CustomUser
    student: CustomUser

    @classmethod
    def setUpTestData(cls):
        cls.school = School.objects.create(name="Emit School")
        cls.teacher = make_user("emit.teacher@emit.edu", school=cls.school)
        cls.student = make_user("emit.kid@example.com", UserTypes.STUDENT)

    def test_one_call_writes_exactly_one_complete_row(self):
        target = uuid.uuid4()
        event = emit(
            AuditAction.ASSIGNMENT_COPY,
            actor=self.teacher,
            target_type="Assignment",
            target_id=target,
            request=request(REMOTE_ADDR="203.0.113.9", HTTP_USER_AGENT="Browser/1.0"),
            metadata={"item_count": 3},
        )
        self.assertEqual(AuditEvent.objects.count(), 1)
        row = AuditEvent.objects.get()
        self.assertEqual(row.pk, event.pk)
        self.assertEqual(row.action, "ASSIGNMENT_COPY")
        self.assertEqual(row.actor_id, self.teacher.id)
        self.assertEqual(row.actor_role, ActorRole.TEACHER)
        self.assertEqual(row.actor_email, "emit.teacher@emit.edu")
        self.assertEqual(row.school_id, self.school.id)
        self.assertEqual(row.target_type, "Assignment")
        self.assertEqual(row.target_id, target)
        self.assertEqual(row.outcome, AuditOutcome.SUCCESS)
        self.assertIsNone(row.error_class)
        self.assertEqual(row.source_ip, "203.0.113.9")
        self.assertEqual(row.user_agent, "Browser/1.0")
        self.assertEqual(row.metadata, {"item_count": 3})
        self.assertEqual(row.retention_class, RetentionClass.GENERAL)
        self.assertIsNotNone(row.occurred_at)

    def test_every_user_type_maps_to_its_role(self):
        for user_type, role in (
            (UserTypes.TEACHER, ActorRole.TEACHER),
            (UserTypes.SCHOOL_ADMIN, ActorRole.SCHOOL_ADMIN),
            (UserTypes.SUPER_ADMIN, ActorRole.SUPER_ADMIN),
            (UserTypes.STUDENT, ActorRole.STUDENT),
        ):
            with self.subTest(user_type=user_type):
                user = make_user(f"role.{str(user_type).lower()}@emit.edu", user_type)
                self.assertEqual(call(actor=user).actor_role, role)

    def test_no_actor_is_a_system_event_with_no_identity(self):
        event = call(actor=None)
        self.assertEqual(event.actor_role, ActorRole.SYSTEM)
        self.assertIsNone(event.actor_id)
        self.assertIsNone(event.actor_email)

    def test_an_anonymous_visitor_is_recorded_as_no_identity(self):
        event = call(actor=AnonymousUser())
        self.assertEqual(event.actor_role, ActorRole.SYSTEM)
        self.assertIsNone(event.actor_id)

    def test_the_actor_is_captured_as_values_and_the_role_is_frozen_at_write_time(self):
        user = make_user("frozen@emit.edu", UserTypes.TEACHER, self.school)
        event = call(actor=user)
        user_id = user.id
        CustomUser.objects.filter(pk=user_id).update(user_type=UserTypes.SCHOOL_ADMIN)
        user.delete()
        event.refresh_from_db()
        self.assertEqual(event.actor_id, user_id)
        self.assertEqual(event.actor_role, ActorRole.TEACHER)
        self.assertEqual(event.actor_email, "frozen@emit.edu")

    def test_an_individual_teacher_has_no_licence(self):
        individual = make_user("solo@example.com")
        self.assertIsNone(call(actor=individual).school_id)

    def test_an_explicit_licence_and_department_are_recorded(self):
        """A super admin acting on behalf of a licence names it."""
        admin = make_user("root@emit.edu", UserTypes.SUPER_ADMIN)
        licence, department = uuid.uuid4(), uuid.uuid4()
        event = call(actor=admin, school_id=licence, department_id=department)
        self.assertEqual(event.school_id, licence)
        self.assertEqual(event.department_id, department)

    def test_the_outcome_and_error_class_are_recorded_for_a_failure(self):
        event = call(
            actor=self.teacher,
            outcome=AuditOutcome.FAILURE,
            error_class=ErrorClass.PROVIDER,
            reason_code="PROVIDER_TIMEOUT",
        )
        self.assertEqual(event.outcome, AuditOutcome.FAILURE)
        self.assertEqual(event.error_class, ErrorClass.PROVIDER)
        self.assertEqual(event.reason_code, "PROVIDER_TIMEOUT")

    def test_before_and_after_are_stored_when_given_and_null_when_not(self):
        event = call(
            actor=self.teacher,
            before={"item_count": 1},
            after={"item_count": 2},
        )
        self.assertEqual(event.before, {"item_count": 1})
        self.assertEqual(event.after, {"item_count": 2})
        plain = call(actor=self.teacher)
        self.assertIsNone(plain.before)
        self.assertIsNone(plain.after)

    def test_a_target_without_an_id_is_allowed(self):
        self.assertIsNone(call(actor=self.teacher, target_id=None).target_id)

    def test_a_string_uuid_target_id_is_accepted(self):
        target = uuid.uuid4()
        self.assertEqual(
            call(actor=self.teacher, target_id=str(target)).target_id, target
        )


class StudentDataTest(TestCase):
    """X-4 and FR-A-04: a student's identity, address and browser are never
    stored, whatever the call site passes."""

    student: CustomUser

    @classmethod
    def setUpTestData(cls):
        cls.student = make_user("kid.real.name@example.com", UserTypes.STUDENT)

    def test_a_student_event_carries_no_email_address_or_browser(self):
        event = call(
            actor=self.student,
            request=request(REMOTE_ADDR="198.51.100.4", HTTP_USER_AGENT="KidBrowser/2"),
        )
        self.assertEqual(event.actor_role, ActorRole.STUDENT)
        self.assertEqual(event.actor_id, self.student.id)
        self.assertIsNone(event.actor_email)
        self.assertIsNone(event.source_ip)
        self.assertIsNone(event.user_agent)

    def test_the_student_email_appears_nowhere_in_the_stored_row(self):
        event = call(
            actor=self.student,
            request=request(REMOTE_ADDR="198.51.100.4"),
            metadata={"item_count": 1},
        )
        stored = " ".join(
            str(getattr(event, f.name)) for f in AuditEvent._meta.get_fields()
        )
        self.assertNotIn("kid.real.name", stored)

    def test_an_email_smuggled_in_metadata_never_reaches_the_table(self):
        key = sorted(ALLOWED_KEYS)[0]
        event = call(actor=self.student, metadata={key: "kid.real.name@example.com"})
        self.assertEqual(event.metadata, {})

    def test_a_student_event_survives_a_student_who_is_later_deleted(self):
        event = call(actor=self.student)
        student_id = self.student.id
        self.student.delete()
        event.refresh_from_db()
        self.assertEqual(event.actor_id, student_id)


class RequestContextTest(TestCase):
    def setUp(self):
        self.teacher = make_user("ctx.teacher@example.org")

    def test_an_invalid_source_address_is_stored_as_null(self):
        event = call(actor=self.teacher, request=request(REMOTE_ADDR="not-an-ip"))
        self.assertIsNone(event.source_ip)

    def test_no_request_means_no_address_or_browser(self):
        event = call(actor=self.teacher)
        self.assertIsNone(event.source_ip)
        self.assertIsNone(event.user_agent)
        self.assertIsNone(event.client_correlation_id)

    def test_an_ipv6_address_is_stored(self):
        event = call(actor=self.teacher, request=request(REMOTE_ADDR="2001:db8::7"))
        self.assertEqual(event.source_ip, "2001:db8::7")

    def test_a_very_long_browser_string_is_cut_to_the_column_size(self):
        event = call(actor=self.teacher, request=request(HTTP_USER_AGENT="A" * 2000))
        self.assertEqual(len(event.user_agent), 512)

    def test_the_address_is_the_one_the_edge_proxy_saw_not_the_one_the_client_claims(
        self,
    ):
        """The same rule the rate limiter uses (NUM_PROXIES): a client that
        sends its own X-Forwarded-For cannot choose the address that ends up in
        the audit trail."""
        forged = request(
            REMOTE_ADDR="10.0.0.1",
            HTTP_X_FORWARDED_FOR="6.6.6.6, 203.0.113.5",
        )
        drf = {**settings.REST_FRAMEWORK, "NUM_PROXIES": 1}
        with override_settings(REST_FRAMEWORK=drf):
            event = call(actor=self.teacher, request=forged)
        self.assertEqual(event.source_ip, "203.0.113.5")

    def test_a_nul_byte_in_the_browser_string_is_removed_so_the_event_still_saves(self):
        """Postgres refuses NUL in text; that would silently lose the event."""
        event = call(actor=self.teacher, request=request(HTTP_USER_AGENT="Bro\x00wser"))
        self.assertEqual(event.user_agent, "Browser")

    def test_an_empty_browser_string_is_stored_as_null(self):
        event = call(actor=self.teacher, request=request(HTTP_USER_AGENT=""))
        self.assertIsNone(event.user_agent)

    def test_the_inbound_request_id_is_kept_as_untrusted_context(self):
        event = call(actor=self.teacher, request=request(HTTP_X_REQUEST_ID="abc-123"))
        self.assertEqual(event.client_correlation_id, "abc-123")

    def test_the_id_the_middleware_attached_is_used_when_present(self):
        req = request()
        req.request_id = "from-middleware"
        self.assertEqual(
            call(actor=self.teacher, request=req).client_correlation_id,
            "from-middleware",
        )

    def test_an_unusable_client_id_is_dropped_not_stored(self):
        for bad in ("has space", "x" * 65, "line\nbreak", "trailing\n", "<script>"):
            with self.subTest(bad=bad):
                req = request()
                req.request_id = bad
                self.assertIsNone(
                    call(actor=self.teacher, request=req).client_correlation_id
                )


class TraceIdTest(TestCase):
    """X-5: the trace id is the server's, never the client's."""

    def test_every_event_gets_its_own_server_generated_trace_id(self):
        first, second = call(), call()
        self.assertIsInstance(first.trace_id, uuid.UUID)
        self.assertNotEqual(first.trace_id, second.trace_id)

    def test_a_client_cannot_choose_the_trace_id_by_sending_one(self):
        """Sending another action's trace id as X-Request-ID must not make this
        event part of that action's trail."""
        victim = call()
        forged = request(HTTP_X_REQUEST_ID=victim.trace_id.hex)
        event = call(request=forged)
        self.assertNotEqual(event.trace_id, victim.trace_id)
        self.assertEqual(event.client_correlation_id, victim.trace_id.hex)

    def test_events_inside_one_trace_context_share_its_id(self):
        with trace_context() as trace_id:
            self.assertEqual(current_trace_id(), trace_id)
            first, second = call(), call()
        self.assertEqual(first.trace_id, trace_id)
        self.assertEqual(second.trace_id, trace_id)
        self.assertIsNone(current_trace_id())
        self.assertNotEqual(call().trace_id, trace_id)

    def test_a_server_supplied_id_is_used_for_a_worker_joining_a_trace(self):
        known = uuid.uuid4()
        with trace_context(known):
            self.assertEqual(call().trace_id, known)
        with trace_context(str(known)):
            self.assertEqual(call().trace_id, known)

    def test_a_garbage_trace_id_is_replaced_rather_than_failing_the_request(self):
        with trace_context("not-a-uuid") as trace_id:
            self.assertIsInstance(trace_id, uuid.UUID)
            self.assertEqual(call().trace_id, trace_id)

    def test_trace_contexts_nest_and_restore(self):
        with trace_context() as outer:
            with trace_context() as inner:
                self.assertNotEqual(outer, inner)
                self.assertEqual(call().trace_id, inner)
            self.assertEqual(call().trace_id, outer)

    def test_outside_any_trace_context_the_requests_own_id_is_used(self):
        """FR-A-03 / NFR-OBS-01: with no explicit trace_context() open, the
        emitter must still land on the SAME id AutoGrader.request_context
        already carries across this request and its Celery tasks - not a
        disconnected random id - so one id reconstructs the whole action."""
        known = uuid.uuid4()
        token = set_request_id(known.hex)
        try:
            self.assertIsNone(current_trace_id())  # no explicit context open
            self.assertEqual(call().trace_id, known)
        finally:
            reset_request_id(token)

    def test_an_explicit_trace_context_still_wins_over_the_requests_own_id(self):
        token = set_request_id(uuid.uuid4().hex)
        try:
            with trace_context() as joined:
                self.assertEqual(call().trace_id, joined)
        finally:
            reset_request_id(token)

    def test_a_non_uuid_shaped_request_id_is_replaced_not_used(self):
        """An inbound X-Request-ID is accepted on a broader charset than a
        UUID for logging (is_valid_request_id) - it must never be assumed to
        be one here just because request_context accepted it."""
        token = set_request_id("not-a-uuid-but-valid-for-logging")
        try:
            event = call()
            self.assertIsInstance(event.trace_id, uuid.UUID)
            self.assertNotEqual(str(event.trace_id), "not-a-uuid-but-valid-for-logging")
        finally:
            reset_request_id(token)

    def test_with_no_request_context_and_no_explicit_trace_a_fresh_id_is_minted(self):
        self.assertIsNone(get_request_id())
        self.assertIsNone(current_trace_id())
        self.assertIsInstance(call().trace_id, uuid.UUID)


