class DatabaseUnreachableTest(TransactionTestCase):
    """The harder case: not a broken table but no database at all."""

    def test_an_unreachable_database_does_not_raise(self):
        settings_dict = connection.settings_dict
        original_port = settings_dict["PORT"]
        original_timeout = settings_dict["OPTIONS"].get("connect_timeout")
        connection.close()
        settings_dict["PORT"] = "1"  # nothing listens here
        settings_dict["OPTIONS"]["connect_timeout"] = 2
        try:
            with self.assertLogs("audit.emitter", level="ERROR"):
                self.assertIsNone(call())
        finally:
            settings_dict["PORT"] = original_port
            if original_timeout is None:
                settings_dict["OPTIONS"].pop("connect_timeout", None)
            else:
                settings_dict["OPTIONS"]["connect_timeout"] = original_timeout
            connection.close()
        self.assertEqual(AuditEvent.objects.count(), 0)
        self.assertIsNotNone(call())


