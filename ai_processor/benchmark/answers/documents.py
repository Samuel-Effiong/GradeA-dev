"""Deterministic PDF fixtures for the answer-extraction benchmark.

Fixtures are GENERATED, not committed as binaries, for three reasons: the
corpus needs dozens of page-count variants (a committed set would be
megabytes of near-duplicates), the page layout has to be derivable from
the same scenario metadata the expectations are built from, and a
generated document can be regenerated byte-identically on any machine -
which is what makes the determinism tests meaningful.

Every random choice is seeded from the scenario id, so the same scenario
always produces the same bytes. Nothing here reads the filesystem, the
working directory, or any external state.

ON "HANDWRITTEN" FIXTURES - AN HONEST LIMIT

There is no handwriting font on this machine (checked: the only
script-ish faces installed are Noto Inscriptional Parthian/Pahlavi). The
`Ink.HANDWRITTEN` style is therefore a SYNTHETIC approximation - an
oblique face with per-glyph baseline jitter, rotation and background
noise. It exercises the pipeline on irregular, low-contrast, hard-to-read
input, which is what the deterministic suite needs.

It does NOT validate the model's handwriting transcription, and no test in
this package claims that it does. Genuine handwriting validation needs
real scanned scripts, which are student data and are not in the
repository; that gap is recorded in README.md under Known limitations.
"""

from __future__ import annotations

import hashlib
import io
import math
from dataclasses import dataclass, field
from enum import Enum

import fitz


class Ink(str, Enum):
    """How answer text is rendered onto the page."""

    TYPED = "typed"
    #: Synthetic irregular writing - see the module docstring's honest limit.
    HANDWRITTEN = "handwritten"
    #: Typed, then degraded: noise, skew and reduced contrast.
    NOISY = "noisy"


@dataclass(frozen=True)
class Line:
    """One line of content to place on a page."""

    text: str
    ink: Ink = Ink.TYPED
    #: Marks this line as belonging to a question, for page attribution.
    question: str | None = None


@dataclass(frozen=True)
class Page:
    lines: tuple[Line, ...] = ()
    #: Rotate the whole page, in degrees. Exercises the rasterizer.
    rotation: int = 0
    #: 0.0 = clean, 1.0 = heavily degraded.
    noise: float = 0.0
    #: An extra non-text block, to make a page image-heavy.
    figure: bool = False


@dataclass(frozen=True)
class Document:
    """A complete generated script."""

    scenario_id: str
    pages: tuple[Page, ...] = field(default=())

    @property
    def page_count(self) -> int:
        return len(self.pages)


def _seed(scenario_id: str) -> int:
    """A stable integer seed from the scenario id."""
    digest = hashlib.sha256(scenario_id.encode("utf-8")).digest()
    return int.from_bytes(digest[:4], "big")


def _jitter(seed: int, index: int, spread: float) -> float:
    """
    Deterministic pseudo-random offset in [-spread, +spread].

    A hash rather than `random`, so no global RNG state is touched and the
    value depends only on (seed, index) - which keeps generation
    reproducible even if tests run in a different order or in parallel.
    """
    raw = hashlib.sha256(f"{seed}:{index}".encode("utf-8")).digest()
    unit = (int.from_bytes(raw[:2], "big") / 0xFFFF) * 2 - 1
    return unit * spread


def _font_for(ink: Ink) -> str:
    # Base-14 names, so no font file is needed and output is identical
    # everywhere. "tiit" (Times italic) stands in for irregular writing.
    return {
        Ink.TYPED: "helv",
        Ink.NOISY: "helv",
        Ink.HANDWRITTEN: "tiit",
    }[ink]


def _render_page(document: fitz.Document, page_spec: Page, seed: int, page_index: int):
    page = document.new_page()
    y = 84.0

    for line_index, line in enumerate(page_spec.lines):
        index = page_index * 1000 + line_index
        if line.ink is Ink.HANDWRITTEN:
            # Per-glyph jitter: irregular baselines and spacing, the thing
            # that makes real writing hard to segment.
            x = 60.0
            for char_index, char in enumerate(line.text):
                page.insert_text(
                    (
                        x + _jitter(seed, index + char_index, 0.9),
                        y + _jitter(seed, index + char_index * 7, 2.6),
                    ),
                    char,
                    fontname=_font_for(line.ink),
                    fontsize=14,
                    rotate=0,
                )
                x += 7.2 + _jitter(seed, index + char_index * 13, 0.7)
            y += 34
        else:
            page.insert_text(
                (60.0, y),
                line.text,
                fontname=_font_for(line.ink),
                fontsize=13,
            )
            y += 30

    if page_spec.figure:
        # A filled shape with a caption: makes the page image-heavy
        # without needing an external asset.
        rect = fitz.Rect(330, 96, 540, 250)
        page.draw_rect(
            rect, color=(0.15, 0.15, 0.15), fill=(0.82, 0.86, 0.9), width=1.2
        )
        for offset in range(0, 150, 12):
            page.draw_line(
                fitz.Point(332, 98 + offset),
                fitz.Point(538, 98 + offset),
                color=(0.55, 0.6, 0.68),
                width=0.4,
            )
        page.insert_text((332, 266), "Figure 1: see diagram", fontsize=10)

    if page_spec.noise > 0:
        _degrade(page, page_spec.noise, seed, page_index)

    if page_spec.rotation:
        page.set_rotation(page_spec.rotation)

    return page


def _degrade(page, level: float, seed: int, page_index: int) -> None:
    """
    Speckle and streaks over the text, plus a wash that lowers contrast.

    Drawn as vector marks rather than by post-processing a bitmap: the
    document has to stay a real PDF so that the production rasterizer
    (pdftoppm, via PDFService) is the thing under test.
    """
    width, height = page.rect.width, page.rect.height
    speckles = int(900 * level)
    for index in range(speckles):
        x = (_jitter(seed, page_index * 7919 + index, 0.5) + 0.5) * width
        y = (_jitter(seed, page_index * 6271 + index, 0.5) + 0.5) * height
        page.draw_circle(
            fitz.Point(x, y),
            0.45 + 0.5 * level,
            color=None,
            fill=(0.35, 0.35, 0.35),
            width=0,
        )
    streaks = int(10 * level)
    for index in range(streaks):
        y = (_jitter(seed, page_index * 5011 + index, 0.5) + 0.5) * height
        page.draw_line(
            fitz.Point(0, y),
            fitz.Point(width, y + _jitter(seed, index, 8)),
            color=(0.6, 0.6, 0.6),
            width=0.6,
        )
    # Contrast wash.
    page.draw_rect(
        page.rect,
        color=None,
        fill=(1, 1, 1),
        fill_opacity=min(0.45, level * 0.5),
        width=0,
    )


def build_document(document: Document) -> bytes:
    """Render a Document spec to PDF bytes. Deterministic for a given spec."""
    seed = _seed(document.scenario_id)
    pdf = fitz.open()
    try:
        for page_index, page_spec in enumerate(document.pages):
            _render_page(pdf, page_spec, seed, page_index)
        if pdf.page_count == 0:
            # A zero-page PDF is a real input case (see the invalid-input
            # scenarios); fitz cannot save one, so emit a valid single-page
            # file and let the caller truncate it if a truly empty file is
            # what is wanted.
            pdf.new_page()
        buffer = io.BytesIO()
        # no_new_id: PyMuPDF otherwise writes a fresh random /ID into the
        # trailer on every save, so two builds of the same spec differed by
        # a few bytes and "the same scenario always produces the same bytes"
        # was false. Found by DeterminismTest; the rendered pages were
        # unaffected, which is why every other suite still passed.
        pdf.save(buffer, no_new_id=True)
        return buffer.getvalue()
    finally:
        pdf.close()


# --------------------------------------------------------------------------
# Page-layout helpers used by the scenario catalogue
# --------------------------------------------------------------------------


def question_line(number: str, text: str, marks: int = 5) -> Line:
    return Line(f"{number}. {text} ({marks} marks)", question=number)


def answer_line(number: str, text: str, ink: Ink = Ink.TYPED) -> Line:
    return Line(f"   {text}", ink=ink, question=number)


def blank_answer_lines(number: str) -> tuple[Line, ...]:
    """A visibly empty response area under a question."""
    return (
        Line("   " + " " * 40, question=number),
        Line("   " + "_" * 40, question=number),
    )


def continued_marker(number: str) -> Line:
    return Line(f"   (question {number} continued overleaf)", question=number)


def spread_pages(
    scenario_id: str,
    per_page: int,
    entries,
    ink: Ink = Ink.TYPED,
    noise: float = 0.0,
    rotation: int = 0,
    figure_on=(),
) -> Document:
    """
    Lay `entries` out across pages, `per_page` questions to a page.

    entries: iterable of (number, question_text, answer_text_or_None).
    A None answer renders a visibly blank response area.
    """
    pages: list[Page] = []
    batch: list[Line] = []
    count = 0
    for number, question_text, answer_text in entries:
        batch.append(question_line(number, question_text))
        if answer_text is None:
            batch.extend(blank_answer_lines(number))
        else:
            batch.append(answer_line(number, answer_text, ink=ink))
        count += 1
        if count % per_page == 0:
            pages.append(
                Page(
                    lines=tuple(batch),
                    noise=noise,
                    rotation=rotation,
                    figure=len(pages) in figure_on,
                )
            )
            batch = []
    if batch:
        pages.append(
            Page(
                lines=tuple(batch),
                noise=noise,
                rotation=rotation,
                figure=len(pages) in figure_on,
            )
        )
    return Document(scenario_id=scenario_id, pages=tuple(pages))


def padded_to(document: Document, page_count: int) -> Document:
    """
    Extend a document to `page_count` pages with continuation sheets.

    Used by the size matrix: the same question set at many page counts, so
    a chunking difference is the only variable.
    """
    pages = list(document.pages)
    filler_index = 0
    while len(pages) < page_count:
        filler_index += 1
        pages.append(
            Page(
                lines=(Line(f"(continuation sheet {filler_index} - no answers here)"),)
            )
        )
    return Document(scenario_id=document.scenario_id, pages=tuple(pages[:page_count]))


def page_count_of(pdf_bytes: bytes) -> int:
    with fitz.open(stream=pdf_bytes, filetype="pdf") as pdf:
        return pdf.page_count


def expected_chunks(page_count: int, pages_per_chunk: int) -> list[list[int]]:
    """
    The page numbers (1-based) each chunk should contain.

    Computed independently of the production splitter on purpose: the
    chunk-invariant tests compare the production split against THIS, so a
    shared helper would let the same bug satisfy both sides.
    """
    if pages_per_chunk < 1:
        raise ValueError("pages_per_chunk must be at least 1")
    pages = list(range(1, page_count + 1))
    return [
        pages[start : start + pages_per_chunk]
        for start in range(0, len(pages), pages_per_chunk)
    ]


def ceil_div(numerator: int, denominator: int) -> int:
    return int(math.ceil(numerator / denominator)) if denominator else 0
