"""
Renders the benchmark dataset to readable PDFs.

Uses Playwright + KaTeX rather than the project's WeasyPrint path
(assignments/views.py:1994) for one reason: there is no server-side LaTeX
renderer anywhere in this project, so WeasyPrint prints
`$$x = \\frac{-b}{2a}$$` as literal text. These PDFs exist to be read by
a human, so the maths has to be typeset.

This module is deliberately NOT on any scheduled path. The nightly
replay and the weekly live run never import it, so those stay hermetic
and free of a browser dependency. Rendering needs network access on
first use to fetch KaTeX from jsDelivr.
"""

import html as html_module
from pathlib import Path

from ai_processor.benchmark import submissions as submissions_module
from ai_processor.benchmark.dataset import (
    ASSIGNMENTS_BY_KEY,
    OBJECTIVE,
    STUDENTS_BY_KEY,
)

KATEX_VERSION = "0.16.11"
KATEX_CSS = f"https://cdn.jsdelivr.net/npm/katex@{KATEX_VERSION}/dist/katex.min.css"
KATEX_JS = f"https://cdn.jsdelivr.net/npm/katex@{KATEX_VERSION}/dist/katex.min.js"
KATEX_AUTORENDER = (
    f"https://cdn.jsdelivr.net/npm/katex@{KATEX_VERSION}/dist/contrib/"
    "auto-render.min.js"
)

_PAGE_CSS = """
@page { size: A4; margin: 18mm 16mm; }
body {
    font-family: "DejaVu Serif", Georgia, serif;
    font-size: 11.5pt;
    line-height: 1.5;
    color: #111;
}
h1 { font-size: 17pt; margin: 0 0 4pt; }
h2 { font-size: 13pt; margin: 18pt 0 6pt; border-bottom: 1px solid #ccc;
     padding-bottom: 3pt; }
.meta { color: #555; font-size: 9.5pt; margin-bottom: 14pt; }
.instructions { background: #f6f6f4; border-left: 3px solid #999;
                padding: 8pt 12pt; margin-bottom: 18pt; font-size: 10.5pt; }
.question { margin-bottom: 16pt; page-break-inside: avoid; }
.qhead { font-weight: bold; margin-bottom: 4pt; }
.qmeta { color: #666; font-size: 9pt; font-weight: normal; }
ol.options { margin: 6pt 0 0 0; padding-left: 20pt; }
ol.options li { margin-bottom: 2pt; list-style: none; }
.answer { border-left: 3px solid #4a7; background: #f4faf6;
          padding: 8pt 12pt; margin-top: 4pt; }
.blank { color: #a00; font-style: italic; }
.rubric { margin-top: 6pt; font-size: 9.5pt; border-collapse: collapse;
          width: 100%; }
.rubric th, .rubric td { border: 1px solid #ddd; padding: 3pt 6pt;
                         text-align: left; vertical-align: top; }
.rubric th { background: #f0f0ee; }
.footer { margin-top: 20pt; color: #777; font-size: 8.5pt;
          border-top: 1px solid #ddd; padding-top: 6pt; }
"""

_SHELL = """<!doctype html>
<html><head><meta charset="utf-8">
<link rel="stylesheet" href="{css}">
<style>{page_css}</style>
</head><body>
{body}
<script src="{js}"></script>
<script src="{autorender}"></script>
<script>
  renderMathInElement(document.body, {{
    delimiters: [
      {{left: "$$", right: "$$", display: true}},
      {{left: "$", right: "$", display: false}}
    ],
    throwOnError: false
  }});
  window.__katexDone = true;
</script>
</body></html>
"""


def _shell(body):
    return _SHELL.format(
        css=KATEX_CSS,
        js=KATEX_JS,
        autorender=KATEX_AUTORENDER,
        page_css=_PAGE_CSS,
        body=body,
    )


def assignment_html(assignment):
    parts = [
        assignment.title,
        f'<div class="meta">{html_module.escape(assignment.subject)} &middot; '
        f"{len(assignment.questions)} questions &middot; "
        f"{assignment.total_points} marks total</div>",
        f'<div class="instructions">{assignment.instructions}</div>',
    ]
    for question in assignment.questions:
        parts.append('<div class="question">')
        parts.append(
            f'<div class="qhead">Question {question["question_number"]} '
            f'<span class="qmeta">({question["points"]} marks &middot; '
            f'{question["question_type"]})</span></div>'
        )
        parts.append(question["question_text"])
        if question["question_type"] == OBJECTIVE:
            parts.append('<ol class="options">')
            for option in question["options"]:
                parts.append(f"<li>{option}</li>")
            parts.append("</ol>")
        elif question["rubric"]:
            parts.append(
                '<table class="rubric"><tr><th>Level</th><th>Marks</th>'
                "<th>Criteria</th></tr>"
            )
            for level in question["rubric"]:
                parts.append(
                    f'<tr><td>{html_module.escape(level["level"])}</td>'
                    f'<td>{level["points"]}</td><td>{level["description"]}</td></tr>'
                )
            parts.append("</table>")
        parts.append("</div>")
    parts.append(
        '<div class="footer">Benchmark assignment — generated by '
        "<code>manage.py grading_benchmark --pdf</code>. Not a real "
        "assessment.</div>"
    )
    return _shell("\n".join(parts))


def submission_html(assignment, student):
    specs = submissions_module.answers_for(assignment.key, student.key)
    expected = submissions_module.expected_total(assignment.key, student.key)
    parts = [
        f"<h1>{html_module.escape(student.name)} — "
        f"{html_module.escape(assignment.subject)}</h1>",
        f'<div class="meta">Submission for: {assignment.title} '
        f"&middot; expected mark {expected:g} / {assignment.total_points}</div>",
        f'<div class="instructions"><b>Student profile:</b> '
        f"{html_module.escape(student.profile)}</div>",
    ]
    for spec in specs:
        question = assignment.question(spec.question_number)
        parts.append('<div class="question">')
        parts.append(
            f'<div class="qhead">Question {question["question_number"]} '
            f'<span class="qmeta">({question["points"]} marks &middot; '
            f"expected {spec.expected_points:g}"
            f'{" &middot; exact" if spec.exact else " &middot; ±1 level"})'
            "</span></div>"
        )
        parts.append(question["question_text"])
        if spec.answer_html.strip():
            parts.append(f'<div class="answer">{spec.answer_html}</div>')
        else:
            parts.append('<div class="answer blank">[no answer submitted]</div>')
        parts.append("</div>")
    parts.append(
        '<div class="footer">Benchmark submission — the "expected" marks are '
        "the hand-authored ground truth this student's answers were written to "
        "hit, not marks awarded by the system.</div>"
    )
    return _shell("\n".join(parts))


def _launch_chromium(playwright):
    """
    Launch Chromium, falling back to whatever build is actually present.

    Playwright pins an exact browser build number per release, so a cache
    populated by a different playwright version fails with "Executable
    doesn't exist" even though a perfectly usable Chromium is sitting
    right there. Rather than force a ~150MB re-download for a PDF that
    renders fine either way, fall back to the newest installed build.
    """
    try:
        return playwright.chromium.launch()
    except Exception:
        candidates = sorted(
            Path.home().glob(".cache/ms-playwright/chromium-*/chrome-linux*/chrome")
        )
        if not candidates:
            raise
        return playwright.chromium.launch(executable_path=str(candidates[-1]))


def render_all(out_dir):
    """
    Write every assignment and submission PDF into `out_dir`.

    Returns the list of written paths. Raises with a clear message if
    Playwright or its browser is unavailable, so a missing browser never
    looks like a benchmark failure.
    """
    try:
        from playwright.sync_api import sync_playwright
    except ImportError as exc:  # pragma: no cover - environment dependent
        raise RuntimeError(
            "playwright is not installed. PDF rendering is optional; the "
            "benchmark itself does not need it."
        ) from exc

    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written = []

    pages = []
    for assignment in ASSIGNMENTS_BY_KEY.values():
        pages.append(
            (out / f"assignment_{assignment.key}.pdf", assignment_html(assignment))
        )
    for assignment in ASSIGNMENTS_BY_KEY.values():
        for student in STUDENTS_BY_KEY.values():
            pages.append(
                (
                    out / f"submission_{assignment.key}_{student.key}.pdf",
                    submission_html(assignment, student),
                )
            )

    try:
        with sync_playwright() as playwright:
            browser = _launch_chromium(playwright)
            try:
                page = browser.new_page()
                for path, html in pages:
                    page.set_content(html, wait_until="networkidle")
                    # KaTeX typesets after load; without this the PDF can
                    # capture raw "$...$" mid-render.
                    page.wait_for_function("window.__katexDone === true")
                    page.pdf(path=str(path), format="A4", print_background=True)
                    written.append(path)
            finally:
                browser.close()
    except Exception as exc:  # pragma: no cover - environment dependent
        raise RuntimeError(
            f"Playwright rendering failed ({type(exc).__name__}: {exc}). "
            "Chromium may be missing — install with `playwright install "
            "chromium` — or the KaTeX CDN may be unreachable."
        ) from exc

    return written
